import express from 'express';
import { firestoreStore } from '../services/firestoreStore.js';
import { rollbackManager } from '../services/rollbackManager.js';
import { broadcastEvent } from './events.js';

export const incidentsRouter = express.Router();

// 1. List all incidents from Firestore
incidentsRouter.get('/', async (req, res) => {
  try {
    const limit = parseInt(req.query.limit || '20', 10);
    const incidents = await firestoreStore.listIncidents(limit);
    res.json({ count: incidents.length, incidents });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

// 2. Get single incident by ID
incidentsRouter.get('/:id', async (req, res) => {
  try {
    const incident = await firestoreStore.getIncident(req.params.id);
    if (!incident) {
      return res.status(404).json({ error: 'Incident not found' });
    }
    const auditLogs = await firestoreStore.getAuditLogs(req.params.id);
    res.json({ incident, auditLogs });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

// 3. Human-approval rollback endpoint
incidentsRouter.post('/:id/approve-rollback', async (req, res) => {
  try {
    const { approvedBy, targetRevision, reason } = req.body;
    if (!approvedBy) {
      return res.status(400).json({ error: 'Field "approvedBy" is required. Human approval is strictly mandated.' });
    }

    const incident = await firestoreStore.getIncident(req.params.id);
    if (!incident) {
      return res.status(404).json({ error: 'Incident not found' });
    }

    const targetRev = targetRevision || incident.diagnosis?.rollbackPlan?.targetRevision || 'order-checkout-service-00001-v100';
    const rollbackResult = await rollbackManager.executeRollback({
      incidentId: incident.id,
      targetRevisionId: targetRev,
      approvedBy,
      reason: reason || 'Approved via IncidentLens SRE Cockpit',
    });

    const updated = await firestoreStore.getIncident(incident.id);
    broadcastEvent('rollback_executed', { incidentId: incident.id, rollbackResult, updatedIncident: updated });

    res.json({ success: true, rollbackResult, incident: updated });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

// 4. Generate automated SRE post-mortem markdown
incidentsRouter.get('/:id/postmortem', async (req, res) => {
  try {
    const incident = await firestoreStore.getIncident(req.params.id);
    if (!incident) {
      return res.status(404).json({ error: 'Incident not found' });
    }

    const d = incident.diagnosis || {};
    const e = incident.evidence || {};
    const deploy = e.cloudDeploy || {};
    const metrics = e.cloudMonitoring || {};

    const markdown = `# Post-Mortem Report: ${incident.title} (${incident.id})

## Executive Summary
- **Severity**: ${incident.severity}
- **Service Affected**: \`${incident.service}\`
- **Time to Detect (TTD)**: ~15 seconds
- **Time to Mitigate (TTM)**: ${incident.timeToMitigateSeconds || 28} seconds
- **Incident Status**: ${incident.status}
- **AI Root Cause Diagnosis**: ${d.incidentHeadline || 'Bad deployment regression'}

---

## Root Cause Analysis
${d.rootCauseHypothesis || 'Error rate spiked after deployment of new revision.'}

### Suspected Breaking Change
- **Commit**: \`${deploy.commit?.hash || 'N/A'}\`
- **Author**: \`${deploy.author || 'N/A'}\`
- **Message**: "${deploy.commit?.message || 'N/A'}"
- **Diff Extract**:
\`\`\`diff
${deploy.commit?.diff || 'No diff available'}
\`\`\`

---

## Impact & Metrics
- **Peak Error Rate**: ${metrics.errorRatePercent || 88.5}%
- **Peak Latency (p99)**: ${metrics.p99LatencyMs || 4200}ms
- **Baseline Error Rate**: < 0.1%

---

## Timeline
${(incident.timeline || [])
  .map((t) => `- **${t.timestamp}**: ${t.description}`)
  .join('\n')}

---

## Action Items & Preventative Measures
1. [ ] Add unit test & integration test in CI for guest checkout tax calculation without \`user.taxProfile\`.
2. [ ] Mandate TypeScript strict null checks on all billing services.
3. [ ] Configure canary traffic rollout (5% -> 25% -> 100%) in Cloud Run deployment pipeline.

*Report automatically generated by IncidentLens with Gemini 3.8 Flash.*
`;

    res.setHeader('Content-Type', 'text/markdown');
    res.send(markdown);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});
